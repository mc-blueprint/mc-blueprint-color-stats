def mask_description(label, kind):
    """確認する人へ、写真のどの部分を示すかを説明する。"""
    if kind in {"exclusion", "person"} and label in EXCLUSIONS:
        return EXCLUSIONS[label]
    key = label.rsplit("/", 1)[-1]
    name = NAMES.get(key, "名前がまだない部分")
    note = NOTES.get(key, "区別の基準は記録されていません。")
    if kind == "raw":
        missing = ("区別の基準は記録されていません。"
                   if "基準は記録されていません" in note else "")
        return name, (f"最初に{name}らしいと見つけた部分です。{missing}"
                      "周りとの関係を確かめたり、空・人・別の部位との重なりを取り除いたりする前の表示です。")
    return name, (f"{note} 空・人と判定された部分と、"
                  "別の部位と重なって決められない部分は除きます。")
